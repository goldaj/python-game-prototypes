class Player:
    def __init__(self, pos):
        self.spawn = Vector2(pos)
        self.pos = Vector2(pos)
        self.size = Vector2(20, 28)    # default small
        self.big_size = Vector2(28, 40) # after mushroom
        self.vel = Vector2(0, 0)
        self.on_ground = False
        self.coyote_timer = 0.0
        self.jump_buffer = 0.0
        self.facing = 1
        self.is_big = False
        self.alive = True
        self.score = 0

    @property
    def rect(self):
        s = self.big_size if self.is_big else self.size
        return pygame.Rect(self.pos.x - s.x/2, self.pos.y - s.y/2, s.x, s.y)

    def reset(self):
        self.pos = Vector2(self.spawn)
        self.vel = Vector2(0, 0)
        self.on_ground = False
        self.coyote_timer = 0.0
        self.jump_buffer = 0.0
        self.facing = 1
        self.alive = True

    def apply_input(self, keys, dt):
        move = 0
        if keys[pygame.K_LEFT] or keys[pygame.K_a]:
            move -= 1
        if keys[pygame.K_RIGHT] or keys[pygame.K_d]:
            move += 1

        running = keys[pygame.K_LSHIFT] or keys[pygame.K_RSHIFT]

        accel = ACCEL * (RUN_ACCEL_MULT if running else 1.0)
        if move != 0:
            self.facing = move
            # accelerate
            self.vel.x += move * accel * dt
        else:
            # friction: running reduces friction for more inertia
            fr = GROUND_FRICTION * (RUN_FRICTION_MULT if running else 1.0) if self.on_ground else AIR_FRICTION
            if abs(self.vel.x) > 1.0:
                self.vel.x -= self.vel.x * fr * dt
            else:
                self.vel.x = 0.0

        # dynamic max speed based on running
        max_speed = MAX_RUN_SPEED * (RUN_SPEED_MULT if running else 1.0)
        self.vel.x = clamp(self.vel.x, -max_speed, max_speed)

        # jump buffering
        jump_pressed = keys[pygame.K_z] or keys[pygame.K_SPACE] or keys[pygame.K_UP]
        if jump_pressed:
            self.jump_buffer = JUMP_BUFFER

    def physics(self, dt, tilemap, solids):
        # apply gravity
        self.vel.y += GRAVITY * dt
        if self.vel.y > MAX_FALL_SPEED:
            self.vel.y = MAX_FALL_SPEED

        # timers
        if self.on_ground:
            self.coyote_timer = COYOTE_TIME
        else:
            self.coyote_timer = max(0.0, self.coyote_timer - dt)
        self.jump_buffer = max(0.0, self.jump_buffer - dt)

        # check running state for jump boost
        keys = pygame.key.get_pressed()
        running = keys[pygame.K_LSHIFT] or keys[pygame.K_RSHIFT]

        # decide jump: if buffered and allowed -> jump (running increases jump speed)
        if self.jump_buffer > 0 and self.coyote_timer > 0:
            jump_strength = JUMP_SPEED * (RUN_JUMP_MULT if running else 1.0)
            self.vel.y = -jump_strength
            self.on_ground = False
            self.coyote_timer = 0.0
            self.jump_buffer = 0.0

        # integrate horizontal then vertical with collision resolution
        self.pos.x += self.vel.x * dt
        self._resolve_axis(tilemap, solids, axis='x')

        self.pos.y += self.vel.y * dt
        self._resolve_axis(tilemap, solids, axis='y')

    def _resolve_axis(self, tilemap, solids, axis='x'):
        r = self.rect
        tiles = tiles_overlapping_rect(r)
        collided = False
        for tx, ty in tiles:
            if ty < 0 or ty >= len(tilemap) or tx < 0 or tx >= len(tilemap[0]):
                continue
            ch = tilemap[ty][tx]
            if ch == '#':
                tr = rect_from_tile(tx, ty)
                if r.colliderect(tr):
                    collided = True
                    if axis == 'x':
                        if self.vel.x > 0:
                            self.pos.x = tr.left - r.width/2 - 0.001
                            self.vel.x = 0
                        elif self.vel.x < 0:
                            self.pos.x = tr.right + r.width/2 + 0.001
                            self.vel.x = 0
                        r = self.rect
                    else:
                        if self.vel.y > 0:
                            self.pos.y = tr.top - r.height/2 - 0.001
                            self.vel.y = 0
                            self.on_ground = True
                        elif self.vel.y < 0:
                            self.pos.y = tr.bottom + r.height/2 + 0.001
                            self.vel.y = 0
                        r = self.rect
        if not collided and axis == 'y':
            self.on_ground = False

class Enemy:
    def __init__(self, pos, patrol=3):
        self.pos = Vector2(pos)
        self.size = Vector2(24, 20)
        self.vel = Vector2(80, 0)  # patrol speed
        self.start_x = pos[0]
        self.patrol = patrol  # in tiles
        self.alive = True

    @property
    def rect(self):
        return pygame.Rect(self.pos.x - self.size.x/2, self.pos.y - self.size.y/2, self.size.x, self.size.y)

    def update(self, dt, tilemap):
        if not self.alive:
            return
        self.pos.x += self.vel.x * dt
        # reverse if beyond patrol range or hitting wall tile
        left_bound = self.start_x - self.patrol * TILE
        right_bound = self.start_x + self.patrol * TILE
        if self.pos.x < left_bound:
            self.pos.x = left_bound
            self.vel.x *= -1
        if self.pos.x > right_bound:
            self.pos.x = right_bound
            self.vel.x *= -1
        # edge detection: look below ahead of movement
        ahead_x = int((self.pos.x + math.copysign(self.size.x/2 + 2, self.vel.x)) // TILE)
        foot_y = int((self.pos.y + self.size.y/2 + 2) // TILE)
        if 0 <= foot_y < len(tilemap) and 0 <= ahead_x < len(tilemap[0]):
            if tilemap[foot_y][ahead_x] == '.':
                self.vel.x *= -1

class Coin:
    def __init__(self, pos):
        self.pos = Vector2(pos)
        self.size = 10
        self.collected = False

    @property
    def rect(self):
        return pygame.Rect(self.pos.x - self.size/2, self.pos.y - self.size/2, self.size, self.size)

class Mushroom:
    def __init__(self, pos):
        self.pos = Vector2(pos)
        self.size = Vector2(18, 18)
        self.collected = False
        self.vel = Vector2(60, 0)

    @property
    def rect(self):
        return pygame.Rect(self.pos.x - self.size.x/2, self.pos.y - self.size.y/2, self.size.x, self.size.y)

    def update(self, dt, tilemap):
        # simple horizontal movement and gravity
        self.vel.y += GRAVITY * dt
        self.pos += self.vel * dt
        r = self.rect
        tiles = tiles_overlapping_rect(r)
        for tx, ty in tiles:
            if 0 <= ty < len(tilemap) and 0 <= tx < len(tilemap[0]):
                if tilemap[ty][tx] == '#':
                    tr = rect_from_tile(tx, ty)
                    if r.colliderect(tr):
                        if self.vel.y > 0 and r.bottom > tr.top and r.top < tr.top:
                            self.pos.y = tr.top - r.height/2 - 0.001
                            self.vel.y = 0
                        else:
                            self.vel.x *= -1

# ------------------ Tilemap helpers ------------------
def tiles_overlapping_rect(rect):
    x1 = max(0, int(rect.left) // TILE)
    y1 = max(0, int(rect.top) // TILE)
    x2 = int(rect.right) // TILE
    y2 = int(rect.bottom) // TILE
    tiles = []
    for ty in range(y1, y2+1):
        for tx in range(x1, x2+1):
            tiles.append((tx, ty))
    return tiles

# ------------------ Procedural Generation ------------------
def create_empty_tilemap(rows, cols):
    return [ ['.' for _ in range(cols)] for _ in range(rows) ]

def ensure_chunks(tilemap, current_cols, target_cols):
    # append columns until tilemap has at least target_cols columns
    rows = len(tilemap)
    while len(tilemap[0]) < target_cols:
        for r in range(rows):
            tilemap[r].append('.')

def generate_chunk(tilemap, start_col):
    rows = len(tilemap)
    cols = len(tilemap[0])
    # We'll create chunk of CHUNK_WIDTH columns starting at start_col
    for c in range(CHUNK_WIDTH):
        col_index = start_col + c
        # ensure column exists
        if col_index >= len(tilemap[0]):
            for r in tilemap:
                r.append('.')
        # bottom two rows are ground-like occasionally; we'll create ground at fixed baseline
        baseline = rows - 2
        # create ground with occasional gaps (pits)
        # Decide if this column is a pit
        pit_chance = 0.06  # small chance of pit (hole)
        is_pit = random.random() < pit_chance and col_index > 5 * TILE
        if is_pit:
            # leave empty (no ground)
            tilemap[baseline][col_index] = '.'
            tilemap[baseline+1][col_index] = '.'
        else:
            tilemap[baseline][col_index] = '#'
            tilemap[baseline+1][col_index] = '#'
        # floating platforms: occasionally place short platforms above baseline
        if random.random() < PLATFORM_PROB:
            plat_height = random.randint(3, 6)  # tiles above baseline
