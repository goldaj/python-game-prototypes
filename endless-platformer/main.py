class Game:
    def __init__(self, screen):
        self.screen = screen
        self.clock = pygame.time.Clock()
        self.font = pygame.font.SysFont(None, 24)
        self.bigfont = pygame.font.SysFont(None, 48)
        self.lives = START_LIVES
        # start tilemap: make room (rows) and a few columns
        rows = 11
        cols = 40
        self.tilemap = create_empty_tilemap(rows, cols)
        # create initial ground baseline
        baseline = rows - 2
        for x in range(cols):
            self.tilemap[baseline][x] = '#'
            self.tilemap[baseline+1][x] = '#'
        # spawn player at left
        px = TILE*3 + TILE/2
        py = baseline * TILE - TILE/2
        self.player = Player((px, py))
        # objects lists
        self.enemies = []
        self.coins = []
        self.mushrooms = []
        # Generate initial procedural chunks to the right
        self.generated_cols = cols
        for i in range(INITIAL_CHUNKS):
            generate_chunk(self.tilemap, self.generated_cols)
            scan_and_spawn_objects(self.tilemap, self.generated_cols, self.generated_cols + CHUNK_WIDTH, self)
            self.generated_cols += CHUNK_WIDTH
        # camera
        self.camera = Camera(SCREEN_W, SCREEN_H)
        self.camera.pos = Vector2(self.player.pos.x - SCREEN_W/2, self.player.pos.y - SCREEN_H/2)
        self.running = True
        self.show_help = False

    def ensure_world_up_to(self, col_index):
        # generate until world has columns beyond col_index + margin
        margin_cols = 40
        target = col_index + margin_cols
        if target > len(self.tilemap[0]) - 1:
            # generate chunks until we exceed target
            while len(self.tilemap[0]) <= target:
                generate_chunk(self.tilemap, self.generated_cols)
                scan_and_spawn_objects(self.tilemap, self.generated_cols, self.generated_cols + CHUNK_WIDTH, self)
                self.generated_cols += CHUNK_WIDTH

    def respawn(self):
        self.lives -= 1
        if self.lives <= 0:
            self.game_over()
        else:
            self.player.reset()

    def game_over(self):
        self.lives = START_LIVES
        self.player.score = 0
        # reset world: small reset to initial area (clear objects and tilemap)
        rows = len(self.tilemap)
        cols = 40
        self.tilemap = create_empty_tilemap(rows, cols)
        baseline = rows - 2
        for x in range(cols):
            self.tilemap[baseline][x] = '#'
            self.tilemap[baseline+1][x] = '#'
        px = TILE*3 + TILE/2
        py = baseline * TILE - TILE/2
        self.player = Player((px, py))
        self.enemies = []
        self.coins = []
        self.mushrooms = []
        self.generated_cols = cols
        for i in range(INITIAL_CHUNKS):
            generate_chunk(self.tilemap, self.generated_cols)
            scan_and_spawn_objects(self.tilemap, self.generated_cols, self.generated_cols + CHUNK_WIDTH, self)
            self.generated_cols += CHUNK_WIDTH

    def update(self, dt):
        keys = pygame.key.get_pressed()
        if keys[pygame.K_ESCAPE]:
            self.running = False
            return

        if keys[pygame.K_h]:
            self.show_help = True
        else:
            self.show_help = False

        # ensure world extends ahead of player
        current_col = int(self.player.pos.x // TILE)
        self.ensure_world_up_to(current_col + CHUNK_WIDTH*2)

        # player input
        self.player.apply_input(keys, dt)
        # variable jump: reduce upward velocity if jump key released for snappier jumps
        jump_released = not (keys[pygame.K_z] or keys[pygame.K_SPACE] or keys[pygame.K_UP])
        if jump_released and self.player.vel.y < 0:
            self.player.vel.y += GRAVITY * dt * 0.9

        # physics update
        self.player.physics(dt, self.tilemap, solids=['#'])

        # enemies update
        for e in self.enemies:
            e.update(dt, self.tilemap)

        # mushrooms update and collection
        for m in self.mushrooms:
            if not m.collected:
                m.update(dt, self.tilemap)
                if self.player.rect.colliderect(m.rect):
                    m.collected = True
                    self.player.is_big = True

        # coins collection
        for c in self.coins:
            if not c.collected and self.player.rect.colliderect(c.rect):
                c.collected = True
                self.player.score += 100

        # enemy collisions
        for e in self.enemies:
            if not e.alive: continue
            if self.player.rect.colliderect(e.rect):
                # stomp if player is falling onto enemy
                player_bottom = self.player.pos.y + (self.player.big_size.y/2 if self.player.is_big else self.player.size.y/2)
                enemy_top = e.pos.y - e.size.y/2
                if self.player.vel.y > 0 and player_bottom - 6 < enemy_top:
                    e.alive = False
                    self.player.vel.y = -JUMP_SPEED * 0.45
                    self.player.score += 200
                else:
                    if self.player.is_big:
                        self.player.is_big = False
                        self.player.vel = Vector2(-self.player.facing * 200, -200)
                    else:
                        self.player.reset()
                        self.respawn()

        # fall below -> respawn
        world_height = len(self.tilemap) * TILE
        if self.player.pos.y > world_height + 200:
            self.player.reset()
            self.respawn()

        # update camera to follow
        self.camera.update(Vector2(self.player.pos.x, self.player.pos.y))

    def draw(self):
        surf = self.screen
        surf.fill(SKY)
        cam = self.camera.pos

        # draw tilemap
        rows = len(self.tilemap)
        cols = len(self.tilemap[0])
        for y in range(rows):
            for x in range(cols):
                if self.tilemap[y][x] == '#':
                    r = rect_from_tile(x, y)
                    draw_rect_world(surf, r, cam, PLATFORM)
                    top = pygame.Rect(r.left, r.top, r.width, 6)
                    draw_rect_world(surf, top, cam, (90, 60, 30))

        # draw coins
        for c in self.coins:
            if c.collected: continue
            p = Vector2(c.pos.x - cam.x, c.pos.y - cam.y)
            if -50 < p.x < SCREEN_W+50 and -50 < p.y < SCREEN_H+50:
                pygame.draw.circle(surf, COIN_COLOR, (int(p.x), int(p.y)), c.size//2)

        # draw mushrooms
        for m in self.mushrooms:
            if m.collected: continue
            p = Vector2(m.pos.x - cam.x, m.pos.y - cam.y)
            if -50 < p.x < SCREEN_W+50 and -50 < p.y < SCREEN_H+50:
                rect = pygame.Rect(p.x - m.size.x/2, p.y - m.size.y/2, m.size.x, m.size.y)
                pygame.draw.rect(surf, POWER_COLOR, rect)
                pygame.draw.rect(surf, (120,40,120), rect.inflate(-6,-6))

        # draw enemies
        for e in self.enemies:
            if not e.alive: continue
            p = Vector2(e.pos.x - cam.x, e.pos.y - cam.y)
            if -50 < p.x < SCREEN_W+50:
                rect = pygame.Rect(p.x - e.size.x/2, p.y - e.size.y/2, e.size.x, e.size.y)
                pygame.draw.rect(surf, ENEMY_COLOR, rect)
                eye = pygame.Rect(p.x + (4 * math.copysign(1, e.vel.x)) - cam.x, p.y - e.size.y/4 - cam.y, 4, 4)
                pygame.draw.rect(surf, (255,255,255), eye)

        # draw player
        s = self.player.big_size if self.player.is_big else self.player.size
        p = Vector2(self.player.pos.x - cam.x, self.player.pos.y - cam.y)
        rect = pygame.Rect(p.x - s.x/2, p.y - s.y/2, s.x, s.y)
        col = PLAYER_BIG if self.player.is_big else PLAYER_COLOR
        pygame.draw.rect(surf, col, rect)
        eye_x = rect.centerx + (6 * self.player.facing)
        pygame.draw.circle(surf, (255,255,255), (int(eye_x), int(rect.centery - 6)), 3)

        # HUD
        self.draw_hud()

        # help overlay
        if self.show_help:
            self.draw_help()

    def draw_hud(self):
        s = self.screen
        score_surf = self.font.render(f"Score: {self.player.score}", True, TEXT_COLOR)
        lives_surf = self.font.render(f"Lives: {self.lives}", True, TEXT_COLOR)
        pos_surf = self.font.render(f"X: {int(self.player.pos.x)} Y: {int(self.player.pos.y)}", True, TEXT_COLOR)
        run_hint = self.font.render(f"Hold SHIFT to run (affects speed & jump)", True, TEXT_COLOR)
        s.blit(score_surf, (12, 8))
        s.blit(lives_surf, (12, 34))
        s.blit(pos_surf, (12, 58))
        s.blit(run_hint, (12, 84))

    def draw_help(self):
        s = self.screen
        lines = [
            "Controls: ←/→ or A/D to move, SHIFT to run, Z/Space/Up to jump (hold for higher jump)",
            "Stomp enemies to defeat them. Collect coins for score. Mushrooms make you big.",
            "This version generates endless platforms to the right. Explore!"
        ]
        box = pygame.Surface((SCREEN_W - 120, 120))
        box.set_alpha(220)
        box.fill((240,240,240))
        s.blit(box, (60, SCREEN_H - 160))
        for i,l in enumerate(lines):
            txt = self.font.render(l, True, (20,20,20))
            s.blit(txt, (72, SCREEN_H - 148 + i*24))

    def run(self):
        while self.running:
            dt = self.clock.tick(FPS) / 1000.0
            for ev in pygame.event.get():
                if ev.type == pygame.QUIT:
                    self.running = False
                if ev.type == pygame.KEYDOWN:
                    if ev.key == pygame.K_r:
                        self.player.reset()
                    if ev.key == pygame.K_ESCAPE:
                        self.running = False

            self.update(dt)
            self.draw()
            pygame.display.flip()

