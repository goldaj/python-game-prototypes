# Scan tilemap columns from start_col to end_col and spawn objects
def scan_and_spawn_objects(tilemap, start_col, end_col, game):
    rows = len(tilemap)
    baseline = rows - 2
    for x in range(start_col, end_col):
        if x < 0 or x >= len(tilemap[0]): continue
        # spawn coins just above any '#' with some probability
        for y in range(rows):
            ch = tilemap[y][x]
            if ch == '#':
                # coin above platform
                if random.random() < COIN_PROB and y > 0:
                    cx = x * TILE + TILE/2
                    cy = y * TILE - TILE//2
                    game.coins.append(Coin((cx, cy)))
                # small chance to spawn enemy on platform top (only at baseline or floating platforms)
                if random.random() < ENEMY_PROB and y < baseline + 2:
                    ex = x * TILE + TILE/2
                    ey = y * TILE + TILE/2 - TILE//2
                    # avoid spawning too many enemies overlapping
                    game.enemies.append(Enemy((ex, ey), patrol=random.randint(2, 5)))
                # mushrooms very rare
                if random.random() < MUSHROOM_PROB:
                    mx = x * TILE + TILE/2
                    my = y * TILE - TILE//2
                    game.mushrooms.append(Mushroom((mx, my)))

